import random
import time
from typing import Dict


def run_random_genesis() -> Dict:
    # 采用当前纳秒级时间戳作为真正随机种子
    seed = int(time.time_ns())
    rng = random.Random(seed)

    cosmic_origins = [
        ("【双星引力潮汐界】", "双恒星互绕形成的引力共振走廊，引力波呈现出有规律的音阶节律。"),
        ("【冷焰暗物质泡】", "位于银河边缘的致密暗物质星云，光线在此处被折射为梦幻般的极光流体。"),
        ("【水墨星环行星】", "拥有由碎冰与硅酸盐尘埃组成的七重光环，地表覆盖着无边无际的深蓝荧光海洋。"),
        ("【晶格熔岩地心界】", "超重力行星内部由超导体结晶构成的庞大脉络，热对流形成了天然的逻辑门回路。")
    ]

    life_forms = [
        ("【深海荧光共生群落】", "由数亿微型发光水母组成的集群意识，通过光斑频闪传递哲学思考。"),
        ("【浮空磁流体羽族】", "在大气层上层滑翔的等离子生命，以雷电为食，身躯如轻纱般透明。"),
        ("【地幔压电硅石人】", "沉睡在地壳深处的硅基长生种，每一次心跳都伴随着一场微型地震。"),
        ("【弦音织梦灵体】", "寄生于时空微小曲率波动中的纯精神生命，以收集智慧生物的顿悟为乐。")
    ]

    milestones = [
        "第一纪：在深海热泉旁筑起首座发光珊瑚神殿，以光斑谱写第一部《海渊法典》。",
        "第二纪：发明【引力风帆】，乘着双星潮汐第一次跃出大气层，点亮了近地轨道。",
        "第三纪：遭遇【超新星高能射线风暴】，全族将意识上传至地幔晶格中，实现了第一次物种形态升华。",
        "第四纪：跨越光年与邻近星系的浮空磁羽族建立【跨维度和鸣同盟】，以声光共振重构了整个星系的能量环。"
    ]

    endings = [
        "【终局·星海合一】：文明彻底脱离实体，化作环绕恒星的一曲永恒极光交响乐。",
        "【终局·归墟方舟】：将全族文明记忆刻入微观质子，向着宇宙深处发射了三万枚探索光锥。",
        "【终局·回溯奇点】：解开时间对称性密码，返航至宇宙大爆炸那一刻，成为最初的引力扰动者。"
    ]

    origin = rng.choice(cosmic_origins)
    life = rng.choice(life_forms)
    ending = rng.choice(endings)

    return {
        "seed": seed,
        "origin": origin,
        "life": life,
        "milestones": milestones,
        "ending": ending
    }


if __name__ == "__main__":
    result = run_random_genesis()
    print("================================================================")
    print(f"      🎲 宇宙随机造物演化实录 (Genesis Seed: {result['seed']}) 🎲      ")
    print("================================================================\n")
    print(f"【起源界域】: {result['origin'][0]} —— {result['origin'][1]}")
    print(f"【始祖生命】: {result['life'][0]} —— {result['life'][1]}\n")
    print("【演化历程】:")
    for m in result["milestones"]:
        print(f"  · {m}")
    print(f"\n【文明终局】: {result['ending']}")
    print("================================================================")
